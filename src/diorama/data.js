export function haversineKm(a, b) {
  const R = 6371;
  const toR = x => x * Math.PI / 180;
  const dLat = toR(b.lat - a.lat);
  const dLng = toR(b.lng - a.lng);
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(toR(a.lat)) * Math.cos(toR(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

export function dayBounds(day) {
  const lats = day.stops.map(s => s.lat);
  const lngs = day.stops.map(s => s.lng);
  return [
    [Math.min(...lngs), Math.min(...lats)],
    [Math.max(...lngs), Math.max(...lats)]
  ];
}

/* ============================================================
 * 실측 투영 — 디오라마와 미니맵이 공유하는 단 하나의 좌표 계산
 * ------------------------------------------------------------
 * 여기서 나온 결과를 3D 배치와 좌하단 미니맵이 함께 쓴다.
 * 그래서 "미니맵과 디오라마가 같은 지도"라는 게 구조적으로 보장된다.
 *
 *   projectDay(day) →
 *     stops[]    스팟별 { km:{x,z}, ci }  — ci = 소속 클러스터 번호
 *     clusters[] 60m 안에 붙어 있는 스팟 묶음 { km:{x,z}, members[] }
 *     lm         랜드마크 km 좌표
 *     centroid   기준점 (위경도)
 *
 * km 좌표계: x = 동쪽(+), z = 남쪽(+). 화면 좌표와 방향이 같다.
 * ============================================================ */

/** 같은 건물·같은 지점으로 볼 반경 (km). 모리미술관 ↔ 도쿄 시티뷰 = 14m */
export const CLUSTER_KM = 0.06;

export function projectDay(day) {
  const stops = day.stops;
  const cLat = stops.reduce((s, g) => s + g.lat, 0) / stops.length;
  const cLng = stops.reduce((s, g) => s + g.lng, 0) / stops.length;
  const kx = 111.32 * Math.cos(cLat * Math.PI / 180);
  const kz = 110.54;
  const toKm = g => ({ x: (g.lng - cLng) * kx, z: -(g.lat - cLat) * kz });

  const km = stops.map(toKm);

  // 60m 안에 붙어 있는 스팟은 하나로 묶는다 (밀어내지 않고 합친다)
  const ci = new Array(stops.length).fill(-1);
  const clusters = [];
  stops.forEach((s, i) => {
    if (ci[i] >= 0) return;
    const members = [i];
    ci[i] = clusters.length;
    for (let j = i + 1; j < stops.length; j++) {
      if (ci[j] >= 0) continue;
      if (haversineKm(s, stops[j]) <= CLUSTER_KM) { ci[j] = clusters.length; members.push(j); }
    }
    clusters.push({
      km: {
        x: members.reduce((a, m) => a + km[m].x, 0) / members.length,
        z: members.reduce((a, m) => a + km[m].z, 0) / members.length
      },
      members
    });
  });

  // 기준점은 평균이 아니라 중앙값을 쓴다.
  // Day 05 처럼 90km 떨어진 스팟이 하나 끼면 평균 중심이 그쪽으로 끌려가고,
  // 나머지 스팟이 전부 한 점으로 뭉개진다. 중앙값은 이상치에 안 흔들린다.
  const med = arr => {
    const s = [...arr].sort((a, b) => a - b);
    const n = s.length;
    return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
  };
  const center = {
    x: med(clusters.map(c => c.km.x)),
    z: med(clusters.map(c => c.km.z))
  };

  return {
    stops: km.map((k, i) => ({ km: k, ci: ci[i] })),
    clusters,
    center,
    lm: day.lm ? toKm(day.lm) : null,
    centroid: { lat: cLat, lng: cLng }
  };
}

/** 하루 총 이동거리 (km) */
export function dayTotalKm(day) {
  let total = 0;
  for (let k = 1; k < day.stops.length; k++) total += haversineKm(day.stops[k - 1], day.stops[k]);
  return total;
}
