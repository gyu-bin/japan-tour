export function streetViewUrl(lat: number, lng: number) {
  return `https://www.google.com/maps/@?api=1&map_action=pano&viewpoint=${lat},${lng}`
}

export function mapsDirUrl(lat: number, lng: number, name: string) {
  const q = encodeURIComponent(`${lat},${lng} (${name})`)
  return `https://www.google.com/maps/dir/?api=1&destination=${q}&travelmode=walking`
}
